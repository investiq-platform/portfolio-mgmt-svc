CREATE TABLE portfolios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id VARCHAR(100) NOT NULL,
    name VARCHAR(120) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_portfolio_owner_name UNIQUE (owner_id, name)
);

CREATE TABLE investment_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id BIGINT NOT NULL REFERENCES portfolios(id) ON DELETE CASCADE,
    scheme_code BIGINT NOT NULL,
    scheme_name VARCHAR(500) NOT NULL,
    transaction_type VARCHAR(20) NOT NULL,
    units NUMERIC(20, 6) NOT NULL CHECK (units > 0),
    nav NUMERIC(20, 6) NOT NULL CHECK (nav > 0),
    occurred_on DATE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_transaction_type CHECK (transaction_type IN ('PURCHASE', 'SIP', 'REDEMPTION'))
);

CREATE INDEX idx_transactions_portfolio_scheme ON investment_transactions (portfolio_id, scheme_code, occurred_on);
